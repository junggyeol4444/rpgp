package com.example.rpgcore.storage.dirty;

/**
 * 지시서 5장 [저장 정책] / 기획서 9장 [즉시 저장 대상 - 확정].
 *
 * <p>되돌릴 수 없거나 재화가 걸린 값만 즉시 저장한다.
 */
public enum SavePriority {

    /**
     * 변경 즉시 저장 큐에 넣는다. 파일 쓰기 자체는 비동기다.
     *
     * <p>대상: 기본 직업 선택 / 1차·2차 전직 확정, 스킬 트리 분기 선택,
     * 스탯 포인트 분배 확정, 스킬 포인트 소비, 특수 재화 증감,
     * 퀘스트 완료 처리 및 보상 지급.
     */
    IMMEDIATE,

    /**
     * 주기 저장 + 접속 종료 시 저장.
     *
     * <p>대상: 전투 경험치·레벨업, 생활 트랙 경험치·레벨업,
     * 스킬 바인딩 변경, 그 외 전부.
     */
    DEFERRED
}
